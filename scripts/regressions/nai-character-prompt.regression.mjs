import assert from 'node:assert/strict';
import { generatePrompt } from '../../packages/client/src/lib/nai-character-prompt/generator.js';
import { SHAPE } from '../../packages/client/src/lib/nai-character-prompt/promptRules.js';
const source = { description: 'A woman with blue eyes.', appearance: 'long black hair' };
const result = structuredClone(SHAPE);
result.subject = [{ value: 'girl', evidence: 'woman' }];
result.appearance.hair = [{ value: 'long black hair', evidence: 'long black hair' }];
result.appearance.eyes = [{ value: 'blue eyes', evidence: 'blue eyes' }];
const calls=[];
const adapter={generate:async(connection,messages)=>{ calls.push({connection,messages});return JSON.stringify(result); }};
assert.deepEqual(await generatePrompt(adapter,'connection',source,new AbortController().signal), {prompt:'girl, long black hair, blue eyes',negative:''});
assert.equal(calls.length,2);
assert.deepEqual(JSON.parse(calls[0].messages[1].content).source,source);
assert.deepEqual(JSON.parse(calls[1].messages[1].content).source,source);
const invalid=structuredClone(result); invalid.appearance.eyes[0].evidence='invented fact';
await assert.rejects(generatePrompt({generate:async()=>JSON.stringify(invalid)},'connection',source), /원문 근거/);
let sent=0;
await assert.rejects(generatePrompt({generate:async()=>{sent++;return '{}';}},'connection',{description:'',appearance:''}), /비어/);
assert.equal(sent,0);
const controller=new AbortController();
await assert.rejects(generatePrompt({generate:async()=>{ controller.abort(); return JSON.stringify(result); }},'connection',source,controller.signal),{name:'AbortError'});
console.log('NAI character prompt v1.3.0 native-core proof passed: evidence, ordering, two raw calls, empty source and cancellation');
